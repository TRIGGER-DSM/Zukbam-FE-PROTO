import { completeFromList, ifNotIn, type Completion } from '@codemirror/autocomplete';

const literalNodes = [
  'Comment',
  'LineComment',
  'BlockComment',
  'String',
  'StringLiteral',
  'TextBlock',
  'CharLiteral',
  'CharacterLiteral',
  'RawString',
];

function languageCompletion(keywords: string[], symbols: Completion[]) {
  const options = [...keywords.map((label) => ({ label, type: 'keyword' })), ...symbols];
  return ifNotIn(literalNodes, completeFromList(options));
}

