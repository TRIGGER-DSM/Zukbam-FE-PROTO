"""Generate lossless WebP assets and responsive sources. Requires Pillow with WebP."""

from pathlib import Path
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'public/images'
DESTINATION = ROOT / 'src/assets/images'
MANIFEST = ROOT / 'src/shared/assets/imageSources.ts'


def main():
    imports = []
    entries = []
    original_bytes = optimized_bytes = 0
    for index, source in enumerate(sorted(SOURCE.rglob('*.png'))):
        relative = source.relative_to(SOURCE)
        destination = (DESTINATION / relative).with_suffix('.webp')
        destination.parent.mkdir(parents=True, exist_ok=True)
        original = Image.open(source).convert('RGBA')
        original.save(destination, 'WEBP', lossless=True, method=6, exact=True)
        with Image.open(destination) as encoded:
            difference = ImageChops.difference(original.convert('RGBa'), encoded.convert('RGBa'))
            assert all(maximum == 0 for _, maximum in difference.getextrema()), source

        name = f'image{index}'
        import_path = f'../../assets/images/{destination.relative_to(DESTINATION).as_posix()}'
        imports.append(f"import {name} from '{import_path}';")
        variants = []
        for width in (480, 960):
            if width >= original.width:
                continue
            resized = original.resize((width, round(original.height * width / original.width)), Image.Resampling.LANCZOS)
            resized_path = destination.with_stem(f'{destination.stem}-{width}')
            resized.save(resized_path, 'WEBP', lossless=True, method=6, exact=True)
            if resized_path.stat().st_size >= destination.stat().st_size:
                resized_path.unlink()
                continue
            variant_name = f'{name}w{width}'
            variant_path = f'../../assets/images/{resized_path.relative_to(DESTINATION).as_posix()}'
            imports.append(f"import {variant_name} from '{variant_path}';")
            variants.append(f'${{{variant_name}}} {width}w')
        variants.append(f'${{{name}}} {original.width}w')
        entries.append(
            f"  '/images/{relative.as_posix()}': {{ src: {name}, width: {original.width}, height: {original.height}, "
            f"srcSet: `{', '.join(variants)}` }},"
        )
        original_bytes += source.stat().st_size
        optimized_bytes += destination.stat().st_size
        print(f'{relative}: {source.stat().st_size:,} -> {destination.stat().st_size:,} bytes')

    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(
        '// Generated by scripts/optimize-images.py.\n' + '\n'.join(imports) + '\n\n'
        'interface ImageSource {\n  src: string;\n  width: number;\n  height: number;\n  srcSet: string;\n}\n\n'
        'export const imageSources: Record<string, ImageSource> = {\n' + '\n'.join(entries) + '\n};\n',
        encoding='utf-8',
    )
    print(f'Full-size raster assets: {original_bytes:,} -> {optimized_bytes:,} bytes ({1 - optimized_bytes / original_bytes:.1%} smaller).')


if __name__ == '__main__':
    main()
